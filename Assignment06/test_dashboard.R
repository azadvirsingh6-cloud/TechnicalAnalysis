# AI-assisted automated tests. Run from Assignment06 after installing packages.
env <- new.env(parent=globalenv()); source("app.R",local=env)
passed <- 0L
check<-function(label,value){if(!isTRUE(value))stop("FAILED: ",label);passed<<-passed+1L;cat("PASS:",label,"\n")}
errors<-function(x)inherits(tryCatch(force(x),error=identity),"error")
equal<-function(a,b)isTRUE(all.equal(a,b,check.attributes=FALSE,tolerance=1e-10))
cat("Azadvir Singh | BDA400 Assignment 6 | AI-assisted real execution\n")
cat("Executed:",format(Sys.time(),tz="America/Toronto"),"America/Toronto\n")
f<-env$fetch_market("AAPL","2024-01-01","2025-12-31","saved");raw<-f$data
check("Offline source identified",grepl("snapshot",f$source))
check("2025 offline input has 250 observations",nrow(raw)==250L)
check("Invalid symbol rejected",errors(env$fetch_market("INVALID","2025-01-01","2025-12-31","saved")))
check("No-overlap offline range rejected",errors(env$fetch_market("AAPL","2020-01-01","2020-12-31","saved")))
check("Invalid timeframe rejected",errors(env$aggregate_bars(raw,"Yearly")))
for(tf in c("Daily","Weekly","Monthly")) {
 a<-env$aggregate_bars(raw,tf)
 check(paste(tf,"volume conserved"),sum(a$Volume)==sum(raw$Volume))
 check(paste(tf,"OHLC consistent"),all(a$High>=pmax(a$Open,a$Close) & a$Low<=pmin(a$Open,a$Close)))
 check(paste(tf,"dates sorted and unique"),!anyDuplicated(a$Date) && all(diff(a$Date)>0))
}
a<-env$aggregate_bars(raw,"Monthly")
check("12 monthly bars",nrow(a)==12L)
jan<-raw[format(raw$Date,"%Y-%m")=="2025-01",]
check("January open/close aggregation",equal(a$Open[1],jan$Open[1]) && equal(a$Close[1],tail(jan$Close,1)))
check("January high/low aggregation",equal(a$High[1],max(jan$High)) && equal(a$Low[1],min(jan$Low)))
d<-env$prepare_data(raw,"Daily","2025-01-01","2025-12-31",20,50,14,"MA crossover")
check("MA alignment",all(is.na(d$SlowMA[1:49])) && equal(d$SlowMA[50],mean(raw$Close[1:50])))
check("Signals limited to Buy Sell Hold",all(d$Signal %in% c("Buy","Sell","Hold")))
check("Warmup never generates events",all(d$Signal[!d$Ready]=="Hold"))
check("Known upward/downward crosses",identical(env$make_signals(c(0,1,2,1,0,2),rep(1,6),rep(1,6),rep(0,6)),c("Hold","Hold","Buy","Hold","Sell","Buy")))
check("Equality is not a crossing",identical(env$make_signals(c(1,1,1),c(1,1,1),1:3,1:3),rep("Hold",3)))
check("MACD confirmation gates buy",identical(env$make_signals(c(0,2),c(1,1),c(-1,-1),c(0,0),"MA + MACD confirmation"),c("Hold","Hold")))
check("Position limited to flat or long",all(d$Position %in% c(0,1)))
i<-which(d$Execution!="None")
check("No same-bar execution",all(i>1) && all(d$Execution[i]==d$Signal[i-1]))
check("Execution at next bar open",equal(d$ExecutionPrice[i],d$Open[i]))
check("Invalid MA ordering rejected",errors(env$prepare_data(raw,"Daily","2025-01-01","2025-12-31",50,20,14,"MA crossover")))
check("Fractional period rejected",errors(env$prepare_data(raw,"Daily","2025-01-01","2025-12-31",2.5,20,14,"MA crossover")))
q4<-env$prepare_data(raw,"Daily","2025-10-01","2025-12-31",20,50,14,"MA crossover")
check("Q4 retains earlier warmup",all(q4$Ready))
check("Q4 date bounds",all(q4$Date>=as.Date("2025-10-01") & q4$Date<=as.Date("2025-12-31")))
check("Q4 indicators match full history",equal(q4$FastMA,d$FastMA[d$Date>=as.Date("2025-10-01")] ))
partial<-env$prepare_data(raw,"Monthly","2025-01-01","2025-06-15",2,3,2,"MA crossover")
check("Monthly cutoff excludes future days",max(partial$Date)<=as.Date("2025-06-15"))
check("Monthly partial last bar close",equal(tail(partial$Close,1),tail(raw$Close[raw$Date<=as.Date("2025-06-15")],1)))
for(type in c("Line","Candlestick","Area")) {
 g<-env$make_price_plot(d,"AAPL",type,c("Moving averages","RSI","MACD"),TRUE,FALSE,20,50)
 check(paste(type,"ggplot builds"),length(ggplot2::ggplot_build(g)$data)>0)
}
