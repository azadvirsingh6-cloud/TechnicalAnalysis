g1<-env$make_price_plot(d,"AAPL","Line",c("Moving averages","RSI","MACD"),TRUE,TRUE,20,50)
check("Indicator toggles add layers",length(g1$layers)>length(g0$layers))
check("Scaled oscillator overlay builds",length(ggplot2::ggplot_build(g1)$data)>0)
check("RSI panel builds",length(ggplot2::ggplot_build(env$make_rsi_plot(d))$data)>0)
check("MACD panel builds",length(ggplot2::ggplot_build(env$make_macd_plot(d))$data)>0)

